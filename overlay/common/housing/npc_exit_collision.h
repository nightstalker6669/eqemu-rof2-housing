inline bool SphereMode(const NpcRuntime::Profile& p){return NpcRuntime::Valid(p)&&std::binary_search(std::begin(HierarchicalPrefixes),std::end(HierarchicalPrefixes),std::string_view(p.model));}
// 5062a0: initial type0 radius H*float(0.5)*float(0.95).
// Later type1 H*0.5*0.35, optional0.9 and/or2, is always smaller.
// Model-option changes leave the committed actor origin fixed. Enclose every
// authenticated original height/control-state radius, not the native placement
// envelope. Original NPC Scale/turns do not multiply this world-space sphere.
inline std::optional<float> Radius(const NpcRuntime::Profile& p){
 if(!SphereMode(p))return {};uint32_t greatest=0;
 for(auto h:p.allowed_heights.height_bits)for(unsigned precision:{24u,53u}){
  auto height=NpcNativeHeight::Decode(h);if(!height)return {};
  auto r=NpcNativeHeight::Multiply(*height,*NpcNativeHeight::Decode(0x3f000000u),precision);
  r=NpcNativeHeight::Multiply(r,*NpcNativeHeight::Decode(0x3f733333u),precision);
  auto bits=NpcNativeHeight::Float32(r);if(!bits||!*bits||*bits>=0x7f800000u)return {};greatest=std::max(greatest,*bits);
 }
 return NpcNativeHeight::Float(greatest);
}
inline ExteriorExit::Box Bounds(const NpcRuntime::Profile& p,const std::optional<NpcNativeFrame::Frame>& frame,const PlacementPolicy::Transform& ground){
 auto radius=Radius(p);if(!radius)throw std::invalid_argument("NPC physical sphere unavailable");
 const auto actor=NpcRuntime::ActorPose(p,ground,frame);const ExteriorExit::Point center{actor.position[1],actor.position[0],actor.position[2]};
 if(!ExteriorExit::Finite(center))throw std::invalid_argument("NPC collision center invalid");
 ExteriorExit::Box out;for(unsigned i=0;i<3;++i){out.minimum[i]=std::nextafter(float(double(center[i])-double(*radius)),-INFINITY);out.maximum[i]=std::nextafter(float(double(center[i])+double(*radius)),INFINITY);}
 if(!ExteriorExit::Finite(out.minimum)||!ExteriorExit::Finite(out.maximum))throw std::invalid_argument("NPC collision bounds overflow");return out;
}
